import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
await fs.mkdir('.local-data/screenshots', { recursive: true });
const browser = await chromium.connectOverCDP('http://127.0.0.1:9223');
const page = browser.contexts()[0].pages()[0];
page.on('pageerror', error => console.error('UI ERROR:', error.message));
await page.reload();
await page.getByRole('heading', { name: 'What needs doing?' }).waitFor();
await page.screenshot({ path: '.local-data/screenshots/project-home.png' });
const original = '.local-data/ui-project/math.cjs';
const before = await fs.readFile(original, 'utf8');
await page.getByRole('button', { name: 'Fix the addition function in math.cjs', exact: true }).click();
await page.getByRole('button', { name: 'Changes 1', exact: true }).waitFor();
await page.getByRole('button', { name: 'Changes 1', exact: true }).click();
await page.locator('.monaco-diff-editor').waitFor();
await page.screenshot({ path: '.local-data/screenshots/diff-review.png' });
await page.getByRole('button', { name: 'Apply changes', exact: true }).click();
await expect(page.getByRole('dialog')).toContainText('Some checks failed');
await page.getByRole('dialog').getByRole('button', { name: 'Apply changes', exact: true }).click();
await expect(page.getByRole('button', { name: 'Undo applied changes', exact: true })).toBeVisible();
if (!(await fs.readFile(original, 'utf8')).includes('return a + b;')) throw new Error('Apply did not change real fixture file');
await page.getByRole('button', { name: 'Undo applied changes', exact: true }).click();
await page.getByRole('dialog').getByRole('button', { name: 'Undo changes', exact: true }).click();
await expect(page.locator('.review-footer')).toContainText('restored');
if (await fs.readFile(original, 'utf8') !== before) throw new Error('Undo did not restore exact original bytes');
console.log('PASS: native Apply / Undo restored real fixture bytes');
await page.getByRole('button', { name: 'Prepare for Codex', exact: true }).click();
await expect(page.getByRole('dialog')).toContainText('Continue this local coding task');
await page.screenshot({ path: '.local-data/screenshots/handoff-preview.png' });
await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
await page.getByRole('button', { name: 'New task', exact: true }).click();
await page.getByRole('button', { name: 'Run tests Check the current project', exact: true }).click();
await page.getByRole('button', { name: 'Start task', exact: false }).click();
await page.getByRole('dialog', { name: "Run this project's code on your PC?" }).waitFor();
await page.screenshot({ path: '.local-data/screenshots/permission.png' });
await page.getByRole('button', { name: 'Allow once', exact: true }).click();
await expect(page.locator('.task-status')).toContainText('Ready for review', { timeout: 20000 });
await page.getByRole('button', { name: 'Checks 1', exact: true }).click();
await expect(page.locator('.check-row')).toContainText('failed');
await expect(page.locator('.check-evidence')).toContainText('AssertionError');
await page.screenshot({ path: '.local-data/screenshots/checks.png' });
console.log('PASS: actual npm test command, approval, failure evidence and native task events');
await page.getByRole('button', { name: 'New task', exact: true }).click();
await page.getByRole('button', { name: 'Search project Find code without a model', exact: true }).click();
await page.getByRole('textbox', { name: 'Task description' }).fill('function add');
await page.getByRole('button', { name: 'Start task', exact: false }).click();
await expect(page.locator('.task-status')).toContainText('Ready for review');
await expect(page.locator('.timeline')).toContainText('search matches');
console.log('PASS: deterministic native search without model');
await page.getByRole('button', { name: 'New task', exact: true }).click();
await page.getByRole('textbox', { name: 'Task description' }).fill('Change authentication and OAuth policy');
await page.getByRole('button', { name: 'Start task', exact: false }).click();
await expect(page.locator('.task-status')).toContainText('Handoff recommended');
console.log('PASS: sensitive task routes to escalation without inference');
await browser.close();
