import { modelIds } from './model-registry.mjs';
import { chromium, expect } from '@playwright/test';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9223');
const page = browser.contexts()[0].pages()[0];
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.getByRole('button',{name:'Settings',exact:true}).first().click();
await page.getByRole('button',{name:'Configure model profiles',exact:true}).click();
await expect(page.getByLabel('Fast model')).toHaveValue(modelIds.fast);
await expect(page.getByLabel('Balanced model')).toHaveValue(modelIds.balanced);
await expect(page.getByLabel('Strong model')).toHaveValue(modelIds.strong);
await expect(page.getByRole('checkbox')).toBeChecked();
await expect(page.getByRole('checkbox')).toBeEnabled();
await expect(page.getByText('Coding test passed',{exact:false})).toHaveCount(3);
await page.screenshot({animations:'disabled',path:'.local-data/screenshots/model-profiles-final.png'});
await page.setViewportSize({width:1000,height:700});
await page.screenshot({animations:'disabled',path:'.local-data/screenshots/model-profiles-narrow.png'});
await page.getByRole('button',{name:'Done',exact:true}).click();
await page.getByRole('button',{name:'New task',exact:true}).click();
await page.getByLabel('Task model').selectOption('@profile/strong');
await page.getByLabel('Task description').fill('Explain math.cjs');
await page.getByRole('button',{name:'Start task',exact:false}).click();
await page.getByRole('dialog',{name:'Use the Strong model for a bounded local attempt?'}).waitFor();
await expect(page.getByRole('dialog')).toContainText('six changed files');
await page.getByRole('button',{name:'Deny',exact:true}).click();
await expect(page.locator('.task-status')).toContainText('Needs attention');
await page.getByRole('button',{name:'New task',exact:true}).click();
await expect(page.getByLabel('Task model')).toHaveValue('auto');
await page.getByRole('button',{name:/Explain a file/}).click();
await page.getByLabel('File to explain').selectOption('math.cjs');
await page.getByLabel('Task description').fill('Explain what this function returns.');
await page.getByRole('button',{name:'Start task',exact:false}).click();
await expect(page.locator('.task-status')).toContainText('Ready for review',{timeout:60000});
await expect(page.locator('.timeline')).toContainText('Using fast');
await expect(page.locator('.timeline')).toContainText(modelIds.fast);
await page.screenshot({animations:'disabled',path:'.local-data/screenshots/real-fast-routing.png'});
await page.setViewportSize({width:1360,height:900});
await page.getByRole('button',{name:'Auto routing',exact:true}).click();
const row=page.locator('.model-row').filter({has:page.getByText(modelIds.balanced,{exact:true})});
await row.getByRole('button',{name:'Test coding',exact:true}).click();
await page.getByRole('button',{name:'Start coding test',exact:true}).click();
await expect(page.getByRole('button',{name:'Stop coding test',exact:true})).toBeVisible();
await expect(page.getByRole('status')).toContainText('Coding fixture passed',{timeout:90000});
await expect(row.getByRole('button',{name:'Test coding',exact:true})).toBeEnabled();
await page.getByRole('button',{name:'Done',exact:true}).click();
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS: all three calibrated assignments, persistent Strong enablement, Strong confirmation/denial, Auto reset, actual Fast inference and actual UI-started coding calibration');
await browser.close();
