import { modelIds } from './model-registry.mjs';
import { chromium, expect } from '@playwright/test';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9223');
const page = browser.contexts()[0].pages()[0];
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await expect(page.getByRole('heading', { name: 'What needs doing?' })).toBeVisible();
await expect(page.getByLabel('Task model')).toHaveValue('auto');
await page.getByRole('button', { name: 'Auto routing', exact: true }).click();
await expect(page.getByLabel('Balanced model')).toHaveValue(modelIds.balanced);
await expect(page.getByRole('checkbox')).toBeDisabled();
await page.getByLabel('Fast model').selectOption(modelIds.balanced);
await page.getByRole('button', { name: 'Save profiles', exact: true }).click();
await expect(page.getByRole('button', { name: 'Save profiles', exact: true })).toBeDisabled();
await expect(page.getByText('Coding test passed', { exact: false }).first()).toBeVisible();
await page.screenshot({ animations: 'disabled', path: '.local-data/screenshots/model-profiles.png' });
await page.getByRole('button', { name: 'Done', exact: true }).click();
await page.reload();
await page.getByRole('button', { name: 'Auto routing', exact: true }).click();
await expect(page.getByLabel('Fast model')).toHaveValue(modelIds.balanced);
await page.getByLabel('Fast model').selectOption('');
await page.getByRole('button', { name: 'Save profiles', exact: true }).click();
await expect(page.getByRole('button', { name: 'Save profiles', exact: true })).toBeDisabled();
const row = page.locator('.model-row').filter({ has: page.getByText(modelIds.balanced, { exact: true }) });
await row.getByRole('button', { name: 'Test coding', exact: true }).click();
await expect(page.getByRole('dialog', { name: 'Test this model on a coding task?' })).toContainText('Windows account');
await page.screenshot({ animations: 'disabled', path: '.local-data/screenshots/model-calibration-approval.png' });
await page.getByRole('dialog', { name: 'Test this model on a coding task?' }).getByRole('button', { name: 'Cancel', exact: true }).click();
await page.getByRole('button', { name: 'Done', exact: true }).click();
if (errors.length) throw Error(errors.join('\n'));
console.log('PASS: native three-profile configuration, persistence, Strong gate and explicit calibration approval');
await browser.close();
